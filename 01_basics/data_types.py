
# My Python Learning Journey
# Topic: Data Types in Python

# 1. String (str) - Text
name = "Vineet"
print("Name:", name)
print("Type:", type(name))

# 2. Integer (int) - Whole numbers
age = 18
print("Age:", age)
print("Type:", type(age))

# 3. Float (float) - Decimal numbers
height = 5.8
print("Height:", height)
print("Type:", type(height))

# 4. Boolean (bool) - True or False
is_student = True
print("Is student:", is_student)
print("Type:", type(is_student))

# 5. List (list) - Collection of items
subjects = ["Python", "Mathematics", "Physics"]
print("Subjects:", subjects)
print("Type:", type(subjects))

# 6. Tuple (tuple) - Ordered collection
coordinates = (10, 20)
print("Coordinates:", coordinates)
print("Type:", type(coordinates))

# 7. Dictionary (dict) - Key-value pairs
student = {
    "name": "Vineet",
    "age": 18,
    "course": "B.Tech CSE"
}
print("Student details:", student)
print("Type:", type(student))

# 8. Set (set) - Collection of unique items
numbers = {1, 2, 3, 3, 4}
print("Numbers:", numbers)
print("Type:", type(numbers))

# 9. NoneType - Represents no value
result = None
print("Result:", result)
print("Type:", type(result))
